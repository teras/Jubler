def auto_translate(lang_code):
    """Auto-translate a single language file"""
    filepath = f"{lang_code}.json"
    
    with open(filepath, 'r', encoding='utf-8') as f:
        data = json.load(f, object_pairs_hook=dict)
    
    translations = TRANSLATIONS.get(lang_code, {})
    updated = 0
    
    for key in data:
        if data[key] == '' and key in translations:
            data[key] = translations[key]
            updated += 1
    
    with open(filepath, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    
    return updated

